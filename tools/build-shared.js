#!/usr/bin/env node
/**
 * tools/build-shared.js
 *
 * Copies the app's SMS-reading files into supabase/functions/_shared/ so
 * the rule-builder on Supabase reads SMS exactly like the phone does.
 *
 *   src/lib/layer2_interpreter.js  ->  _shared/layer2_interpreter.js
 *   src/lib/layer2_ruleset.js      ->  _shared/layer2_ruleset.js
 *   layer1sim.js (found anywhere)  ->  _shared/layer1sim.js
 *
 * The originals stay the only files you edit. Run this before every
 * `supabase functions deploy rule-builder`:
 *
 *   node tools/build-shared.js
 *
 * Why a copy is needed: the app files are written for the phone (CommonJS);
 * Supabase functions need ES modules. The copy wraps each file without
 * changing a single line of it.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const MOBILE = path.resolve(__dirname, '..');
const OUT = path.join(MOBILE, 'supabase', 'functions', '_shared');

function findFile(name) {
  const skip = new Set(['node_modules', '.git', '.expo', 'android', 'ios', 'supabase', 'dist', 'build']);
  const hits = [];
  (function walk(dir, depth) {
    if (depth > 6) return;
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.isDirectory()) { if (!skip.has(e.name)) walk(path.join(dir, e.name), depth + 1); }
      else if (e.name === name) hits.push(path.join(dir, e.name));
    }
  })(MOBILE, 0);
  return hits;
}

const sources = [
  { name: 'layer2_interpreter.js', from: path.join(MOBILE, 'src', 'lib', 'layer2_interpreter.js') },
  { name: 'layer2_ruleset.js', from: path.join(MOBILE, 'src', 'lib', 'layer2_ruleset.js') },
];

const l1 = findFile('layer1sim.js');
if (l1.length === 0) {
  console.error('Stopped: layer1sim.js not found in this folder.');
  process.exit(1);
}
if (l1.length > 1) {
  console.error('Stopped: found more than one layer1sim.js. Keep only one:');
  for (const p of l1) console.error('  ' + path.relative(MOBILE, p));
  process.exit(1);
}
sources.push({ name: 'layer1sim.js', from: l1[0] });

fs.mkdirSync(OUT, { recursive: true });
for (const s of sources) {
  if (!fs.existsSync(s.from)) {
    console.error(`Stopped: ${path.relative(MOBILE, s.from)} not found.`);
    process.exit(1);
  }
  const src = fs.readFileSync(s.from, 'utf8');
  if (/\brequire\s*\(/.test(src)) {
    console.error(`Stopped: ${s.name} now uses require(); the copy can't include other files. Tell Claude.`);
    process.exit(1);
  }
  const rel = path.relative(MOBILE, s.from).replace(/\\/g, '/');
  const wrapped =
    `// GENERATED by tools/build-shared.js from ${rel}. Do not edit this copy:\n` +
    `// edit the original and run "node tools/build-shared.js" again.\n` +
    `// deno-lint-ignore-file\n` +
    `const module = { exports: {} };\n` +
    `const exports = module.exports;\n` +
    src.replace(/^﻿/, '') +
    `\nexport default module.exports;\n`;
  fs.writeFileSync(path.join(OUT, s.name), wrapped);
  console.log(`copied ${rel} -> supabase/functions/_shared/${s.name}`);
}
console.log('Done. Now deploy: npx supabase functions deploy rule-builder --project-ref hpvztbvrwhwdybkmaczs');
