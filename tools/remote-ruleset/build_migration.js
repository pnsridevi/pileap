#!/usr/bin/env node
/**
 * build_migration.js
 *
 *   node build_migration.js [path/to/layer2_ruleset.js] [outDir]
 *
 * Reads the bundled ruleset (for BANK_TOKENS and the 23 plain-regex
 * match patterns), merges with rules_source.js, verifies the result
 * compiles in the interpreter, and writes:
 *   - parse_rules_seed.json   (rows exactly as the app will receive them;
 *                              compare_rulesets.js reads this)
 *   - 002_seed_remote_ruleset.sql
 */

'use strict';

const fs = require('fs');
const path = require('path');
const Module = require('module');
const { RULE_ROWS, FROM_BUNDLED } = require('./rules_source.js');
const { compileRuleset } = require('../../src/lib/layer2_interpreter.js');

const rulesetPath = path.resolve(process.argv[2] || path.join(__dirname, '../../src/lib/layer2_ruleset.js'));
const outDir = path.resolve(process.argv[3] || path.join(__dirname, 'out'));

function loadWithPrivates(file) {
  // BANK_TOKENS isn't exported by the bundled file; expose it for this build only.
  const src = fs.readFileSync(file, 'utf8');
  const m = new Module(file, null);
  m.filename = file;
  m.paths = Module._nodeModulePaths(path.dirname(file));
  m._compile(`${src}\nmodule.exports.__BANK_TOKENS = BANK_TOKENS;`, file);
  return m.exports;
}

const lib = loadWithPrivates(rulesetPath);
const bundledById = Object.fromEntries(lib.RULES.map((r) => [r.id, r]));

// ── Structural checks against the bundled file ──────────────────────────
const bundledIds = lib.RULES.map((r) => r.id);
const sourceIds = RULE_ROWS.map((r) => r.rule_key);
if (JSON.stringify(bundledIds) !== JSON.stringify(sourceIds)) {
  console.error('Rule list/order differs from the bundled file:');
  console.error(' bundled:', bundledIds.join(', '));
  console.error(' source :', sourceIds.join(', '));
  process.exit(1);
}

const rules = RULE_ROWS.map((row, i) => {
  let match = row.match_patterns;
  if (match === FROM_BUNDLED) {
    const p = bundledById[row.rule_key].pattern;
    if (!(p instanceof RegExp)) throw new Error(`${row.rule_key}: FROM_BUNDLED but bundled pattern is a test() object`);
    match = [{ re: p.source, flags: p.flags }];
  } else if (bundledById[row.rule_key].pattern instanceof RegExp) {
    throw new Error(`${row.rule_key}: bundled pattern is a plain RegExp — use FROM_BUNDLED instead of transcribing`);
  }
  return {
    layer: 2,
    rule_key: row.rule_key,
    priority: (i + 1) * 10, // gaps of 10 so a new rule can slot between two existing ones
    match_patterns: match,
    exclude_patterns: row.exclude_patterns || [],
    fixed_fields: row.fixed_fields || {},
    field_overrides: row.field_overrides || {},
  };
});

const aliases = lib.__BANK_TOKENS.map((b, i) => ({
  token: b.token,
  bank_name: b.name,
  priority: (i + 1) * 10,
}));
const dupTokens = aliases.map((a) => a.token).filter((t, i, all) => all.indexOf(t) !== i);
if (dupTokens.length) throw new Error(`duplicate bank tokens: ${dupTokens.join(', ')}`);

// Must compile cleanly in the same interpreter the app runs.
const compiled = compileRuleset({ rules, aliases }, lib);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'parse_rules_seed.json'),
  JSON.stringify({ rules, aliases }, null, 2) + '\n');

// ── SQL ─────────────────────────────────────────────────────────────────
function dq(json) {
  const s = JSON.stringify(json);
  if (s.includes('$j$')) throw new Error('dollar-quote tag collision');
  return `$j$${s}$j$::jsonb`;
}
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const sql = [];
sql.push(`-- ============================================================
-- 002_seed_remote_ruleset.sql
-- Generated by build_migration.js from ${path.basename(rulesetPath)} — do not hand-edit;
-- change rules_source.js and regenerate.
--
-- ${rules.length} Layer 2 rules + ${aliases.length} bank aliases.
-- Every rule is inserted as status = 'draft'. RLS only serves 'active'
-- rows to devices, so nothing here reaches a phone until promoted
-- (see the promotion statement at the bottom, commented out).
--
-- Safe to re-run: upserts on rule_key / token. A re-run updates rule
-- CONTENT but never touches status, so an already-active rule stays
-- active (and picks up the new content immediately — mind that on any
-- project where rules are active).
-- ============================================================

begin;

-- BANK_TOKENS is first-match-wins on substrings: 'southindianbank' must
-- be tried before 'indianbank', 'cityunionbank' before 'unionbank'.
-- bank_aliases had no ordering column, so this adds one.
alter table public.bank_aliases
  add column if not exists priority integer not null default 100;

create index if not exists bank_aliases_priority_idx
  on public.bank_aliases (priority);
`);

sql.push('insert into public.bank_aliases (token, bank_name, priority) values');
sql.push(aliases.map((a) => `  (${lit(a.token)}, ${lit(a.bank_name)}, ${a.priority})`).join(',\n'));
sql.push(`on conflict (token) do update
  set bank_name = excluded.bank_name,
      priority  = excluded.priority;
`);

for (const r of rules) {
  sql.push(`insert into public.parse_rules
  (layer, rule_key, priority, status, match_patterns, exclude_patterns, fixed_fields, field_overrides, notes, created_by)
values (
  ${r.layer}, ${lit(r.rule_key)}, ${r.priority}, 'draft',
  ${dq(r.match_patterns)},
  ${dq(r.exclude_patterns)},
  ${dq(r.fixed_fields)},
  ${dq(r.field_overrides)},
  ${lit('Migrated from ' + path.basename(rulesetPath) + ' (interpreter schema v1)')},
  'build_migration.js'
)
on conflict (rule_key) do update set
  layer            = excluded.layer,
  priority         = excluded.priority,
  match_patterns   = excluded.match_patterns,
  exclude_patterns = excluded.exclude_patterns,
  fixed_fields     = excluded.fixed_fields,
  field_overrides  = excluded.field_overrides,
  notes            = excluded.notes;
`);
}

sql.push(`comment on column public.parse_rules.match_patterns is
  'jsonb array of {"re": <regex source>, "flags": <subset of "imsu">}. Rule fires if ANY matches. AND of two conditions = one regex with a lookahead.';
comment on column public.parse_rules.exclude_patterns is
  'jsonb array of {"re","flags"}. Rule is skipped if ANY matches.';
comment on column public.parse_rules.field_overrides is
  'jsonb {field: {steps: [...], null_if?: [...], rewrite?: [...]}}. Step types: re / helper / value / test / lookup — see layer2_interpreter.js header. Unknown step types make the whole ruleset fail to compile on-device (devices fall back to cache/bundled).';
comment on column public.bank_aliases.priority is
  'Lower is tried first. Order matters: tokens are substring-matched and the first hit wins.';

commit;

-- ── Sanity checks (run after commit) ─────────────────────────────────
-- select count(*) from public.parse_rules where layer = 2;            -- expect ${rules.length}
-- select count(*) from public.bank_aliases;                           -- expect ${aliases.length}
-- select version from public.ruleset_meta;                            -- bumped by triggers

-- ── Promotion (TEST PROJECT ONLY, after compare_rulesets.js passes) ──
-- update public.parse_rules set status = 'active'
--  where layer = 2 and status = 'draft';
`);

fs.writeFileSync(path.join(outDir, '002_seed_remote_ruleset.sql'), sql.join('\n'));

console.log(`OK: ${compiled.ruleKeys.length} rules, ${compiled.aliasCount} bank aliases compiled`);
console.log(`wrote ${path.join(outDir, 'parse_rules_seed.json')}`);
console.log(`wrote ${path.join(outDir, '002_seed_remote_ruleset.sql')}`);